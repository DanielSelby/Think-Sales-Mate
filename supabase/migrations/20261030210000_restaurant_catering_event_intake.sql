begin;

create table if not exists public.restaurant_catering_events (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  location_id uuid not null references public.business_locations(id) on delete restrict,
  event_number bigint generated by default as identity,
  event_name text not null check (length(btrim(event_name)) between 1 and 120),
  customer_name text not null check (length(btrim(customer_name)) between 1 and 120),
  customer_organization text check (customer_organization is null or length(customer_organization) <= 160),
  customer_phone text not null check (length(btrim(customer_phone)) between 7 and 40),
  customer_email text check (customer_email is null or length(customer_email) <= 254),
  starts_at timestamptz not null,
  event_location text not null check (length(btrim(event_location)) between 1 and 300),
  guest_count integer not null check (guest_count between 1 and 10000),
  custom_menu text not null default '' check (length(custom_menu) <= 5000),
  setup_requirements text not null default '' check (length(setup_requirements) <= 2000),
  notes text not null default '' check (length(notes) <= 2000),
  status text not null default 'inquiry'
    check (status in ('inquiry', 'quoted', 'confirmed', 'preparing', 'completed', 'cancelled')),
  created_by uuid not null references auth.users(id),
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, id),
  unique (org_id, event_number)
);

create index if not exists restaurant_catering_events_org_location_start_idx
  on public.restaurant_catering_events(org_id, location_id, starts_at desc);
create index if not exists restaurant_catering_events_org_status_start_idx
  on public.restaurant_catering_events(org_id, status, starts_at);

create table if not exists public.restaurant_catering_event_status_history (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  event_id uuid not null,
  previous_status text check (previous_status is null or previous_status in ('inquiry', 'quoted', 'confirmed', 'preparing', 'completed', 'cancelled')),
  new_status text not null check (new_status in ('inquiry', 'quoted', 'confirmed', 'preparing', 'completed', 'cancelled')),
  changed_by uuid references auth.users(id),
  changed_at timestamptz not null default now(),
  foreign key (org_id, event_id)
    references public.restaurant_catering_events(org_id, id) on delete cascade
);

create index if not exists restaurant_catering_event_status_history_event_idx
  on public.restaurant_catering_event_status_history(org_id, event_id, changed_at desc);

create or replace function public.record_restaurant_catering_event_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.restaurant_catering_event_status_history (
      org_id, event_id, previous_status, new_status, changed_by
    ) values (
      new.org_id, new.id, null, new.status, new.created_by
    );
  elsif new.status is distinct from old.status then
    insert into public.restaurant_catering_event_status_history (
      org_id, event_id, previous_status, new_status, changed_by
    ) values (
      new.org_id, new.id, old.status, new.status, new.updated_by
    );
  end if;
  return new;
end;
$$;

drop trigger if exists restaurant_catering_event_status_history_trigger
  on public.restaurant_catering_events;
create trigger restaurant_catering_event_status_history_trigger
  after insert or update of status on public.restaurant_catering_events
  for each row execute function public.record_restaurant_catering_event_status();
revoke all on function public.record_restaurant_catering_event_status() from public, anon, authenticated;
grant execute on function public.record_restaurant_catering_event_status() to service_role;

alter table public.restaurant_catering_events enable row level security;
alter table public.restaurant_catering_event_status_history enable row level security;

drop policy if exists "Restaurant catering events: members read assigned locations"
  on public.restaurant_catering_events;
create policy "Restaurant catering events: members read assigned locations"
  on public.restaurant_catering_events for select
  using (public.is_org_member(org_id) and public.can_access_org_location(org_id, location_id));

drop policy if exists "Restaurant catering event history: members read assigned locations"
  on public.restaurant_catering_event_status_history;
create policy "Restaurant catering event history: members read assigned locations"
  on public.restaurant_catering_event_status_history for select
  using (
    public.is_org_member(org_id)
    and exists (
      select 1 from public.restaurant_catering_events event
      where event.org_id = restaurant_catering_event_status_history.org_id
        and event.id = restaurant_catering_event_status_history.event_id
        and public.can_access_org_location(restaurant_catering_event_status_history.org_id, event.location_id)
    )
  );

revoke all on public.restaurant_catering_events from public, anon, authenticated;
revoke all on public.restaurant_catering_event_status_history from public, anon, authenticated;
grant select on public.restaurant_catering_events to authenticated;
grant select on public.restaurant_catering_event_status_history to authenticated;
grant all on public.restaurant_catering_events to service_role;
grant all on public.restaurant_catering_event_status_history to service_role;
grant usage, select on sequence public.restaurant_catering_events_event_number_seq to service_role;

commit;
