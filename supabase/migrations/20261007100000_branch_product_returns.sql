create table public.branch_product_returns (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  return_number bigint generated by default as identity,
  source_location_id uuid not null references public.business_locations(id),
  destination_location_id uuid not null references public.business_locations(id),
  return_date date not null default current_date,
  requested_by uuid not null references auth.users(id),
  created_by uuid not null references auth.users(id),
  status text not null default 'pending_review'
    check (status in ('pending_review', 'pending_identification', 'identified', 'consolidated', 'supplier_return_created', 'completed', 'rejected', 'cancelled')),
  return_reason text not null,
  priority text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, return_number),
  check (source_location_id <> destination_location_id)
);

create table public.branch_product_return_items (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  return_id uuid not null references public.branch_product_returns(id) on delete restrict,
  product_id uuid not null references public.products(id),
  return_qty integer not null check (return_qty > 0),
  unit_cost numeric(12, 2) not null check (unit_cost >= 0),
  return_value numeric(14, 2) not null check (return_value >= 0),
  condition text not null,
  return_reason text not null,
  inspection_notes text,
  original_transfer_id uuid references public.stock_transfers(id),
  supplier_id uuid references public.suppliers(id),
  purchase_id uuid references public.purchases(id),
  purchase_item_id uuid references public.purchase_items(id),
  supplier_accepted_qty integer,
  supplier_rejected_qty integer,
  supplier_response_notes text,
  created_at timestamptz not null default now(),
  check ((supplier_id is null and purchase_id is null and purchase_item_id is null)
    or (supplier_id is not null and purchase_id is not null and purchase_item_id is not null)),
  check (supplier_accepted_qty is null or supplier_accepted_qty >= 0),
  check (supplier_rejected_qty is null or supplier_rejected_qty >= 0)
);

create table public.branch_product_return_consolidations (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  consolidation_number bigint generated by default as identity,
  supplier_id uuid not null references public.suppliers(id),
  purchase_id uuid not null references public.purchases(id),
  status text not null default 'ready'
    check (status in ('ready', 'supplier_return_created', 'accepted', 'partially_accepted', 'rejected', 'completed')),
  purchase_return_id uuid references public.purchase_returns(id),
  supplier_accepted_qty integer,
  supplier_rejected_qty integer,
  supplier_response_notes text,
  supplier_responded_by uuid references auth.users(id),
  supplier_responded_at timestamptz,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  unique (org_id, consolidation_number),
  check (supplier_accepted_qty is null or supplier_accepted_qty >= 0),
  check (supplier_rejected_qty is null or supplier_rejected_qty >= 0)
);

create table public.branch_product_return_consolidation_items (
  consolidation_id uuid not null references public.branch_product_return_consolidations(id) on delete restrict,
  return_item_id uuid not null unique references public.branch_product_return_items(id) on delete restrict,
  org_id uuid not null references public.organizations(id) on delete cascade,
  created_at timestamptz not null default now(),
