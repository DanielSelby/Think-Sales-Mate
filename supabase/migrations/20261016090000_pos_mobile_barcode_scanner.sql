create table if not exists public.pos_mobile_scanner_sessions (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  location_id uuid not null references public.business_locations(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete cascade,
  source_module text not null default 'pos' check (source_module in ('pos', 'sales')),
  token_hash text not null unique,
  expires_at timestamptz not null,
  revoked_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists idx_pos_mobile_scanner_sessions_owner
  on public.pos_mobile_scanner_sessions(org_id, created_by, expires_at desc);

create table if not exists public.pos_mobile_barcode_scans (
  sequence_id bigint generated by default as identity primary key,
  session_id uuid not null references public.pos_mobile_scanner_sessions(id) on delete cascade,
  barcode text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_pos_mobile_barcode_scans_session_sequence
  on public.pos_mobile_barcode_scans(session_id, sequence_id);

alter table public.pos_mobile_scanner_sessions enable row level security;
alter table public.pos_mobile_barcode_scans enable row level security;

revoke all on public.pos_mobile_scanner_sessions from anon, authenticated;
revoke all on public.pos_mobile_barcode_scans from anon, authenticated;
grant all on public.pos_mobile_scanner_sessions to service_role;
grant all on public.pos_mobile_barcode_scans to service_role;
grant usage, select on sequence public.pos_mobile_barcode_scans_sequence_id_seq to service_role;
