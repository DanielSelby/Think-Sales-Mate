begin;

create table if not exists public.restaurant_menu_categories (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 100),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, id),
  unique (org_id, name)
);

create table if not exists public.restaurant_menu_items (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  category_id uuid,
  name text not null check (length(btrim(name)) between 1 and 120),
  description text,
  price numeric(12,2) not null check (price >= 0),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, id),
  foreign key (org_id, category_id)
    references public.restaurant_menu_categories(org_id, id) on delete set null (category_id)
);

create table if not exists public.restaurant_tables (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  location_id uuid not null references public.business_locations(id) on delete restrict,
  table_name text not null check (length(btrim(table_name)) between 1 and 40),
  seats integer not null default 2 check (seats between 1 and 100),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, id),
  unique (org_id, location_id, table_name)
);

create table if not exists public.restaurant_orders (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  location_id uuid not null references public.business_locations(id) on delete restrict,
  order_number bigint generated by default as identity,
  order_type text not null check (order_type in ('dine_in', 'takeaway', 'delivery')),
  table_id uuid,
  status text not null default 'new'
    check (status in ('new', 'confirmed', 'preparing', 'ready', 'served', 'completed', 'cancelled')),
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid', 'partial', 'paid')),
  customer_name text,
  customer_phone text,
  delivery_address text,
  notes text,
  subtotal numeric(12,2) not null check (subtotal >= 0),
  total numeric(12,2) not null check (total >= 0),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, id),
  unique (org_id, order_number),
  foreign key (org_id, table_id)
    references public.restaurant_tables(org_id, id) on delete restrict,
  check ((order_type = 'dine_in' and table_id is not null) or (order_type <> 'dine_in' and table_id is null))
);

create table if not exists public.restaurant_order_items (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  order_id uuid not null,
  menu_item_id uuid,
  item_name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity numeric(10,2) not null check (quantity > 0),
  line_total numeric(12,2) not null check (line_total >= 0),
  notes text,
  kitchen_status text not null default 'new'
    check (kitchen_status in ('new', 'preparing', 'ready', 'served', 'cancelled')),
  created_at timestamptz not null default now(),
  unique (org_id, id),
  foreign key (org_id, order_id)
    references public.restaurant_orders(org_id, id) on delete cascade,
  foreign key (org_id, menu_item_id)
    references public.restaurant_menu_items(org_id, id) on delete set null (menu_item_id)
);

create table if not exists public.restaurant_order_payments (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  order_id uuid not null,
  amount numeric(12,2) not null check (amount > 0),
  payment_method text not null check (payment_method in ('cash', 'card', 'mobile_money', 'other')),
  received_by uuid not null references auth.users(id),
  paid_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  foreign key (org_id, order_id)
    references public.restaurant_orders(org_id, id) on delete cascade
);

create index if not exists restaurant_menu_items_org_category_idx
  on public.restaurant_menu_items(org_id, category_id, sort_order, name);
create index if not exists restaurant_tables_org_location_idx
  on public.restaurant_tables(org_id, location_id, is_active, table_name);
create index if not exists restaurant_orders_org_location_created_idx
  on public.restaurant_orders(org_id, location_id, created_at desc);
create index if not exists restaurant_orders_org_status_created_idx
  on public.restaurant_orders(org_id, status, created_at desc);
create unique index if not exists restaurant_orders_one_open_order_per_table_idx
  on public.restaurant_orders(org_id, table_id)
  where table_id is not null and status not in ('completed', 'cancelled');
create index if not exists restaurant_order_items_org_order_idx
  on public.restaurant_order_items(org_id, order_id);
create index if not exists restaurant_order_payments_org_order_idx
  on public.restaurant_order_payments(org_id, order_id, paid_at desc);

alter table public.restaurant_menu_categories enable row level security;
alter table public.restaurant_menu_items enable row level security;
alter table public.restaurant_tables enable row level security;
alter table public.restaurant_orders enable row level security;
alter table public.restaurant_order_items enable row level security;
alter table public.restaurant_order_payments enable row level security;

create policy "Restaurant categories: organization members read"
  on public.restaurant_menu_categories for select
  using (public.is_org_member(org_id));
create policy "Restaurant menu items: organization members read"
  on public.restaurant_menu_items for select
  using (public.is_org_member(org_id));
create policy "Restaurant tables: members read assigned locations"
  on public.restaurant_tables for select
  using (public.is_org_member(org_id) and public.can_access_org_location(org_id, location_id));
create policy "Restaurant orders: members read assigned locations"
  on public.restaurant_orders for select
  using (public.is_org_member(org_id) and public.can_access_org_location(org_id, location_id));
create policy "Restaurant order items: members read authorized orders"
  on public.restaurant_order_items for select
  using (
    public.is_org_member(org_id)
    and exists (
      select 1 from public.restaurant_orders orders
      where orders.org_id = restaurant_order_items.org_id
        and orders.id = restaurant_order_items.order_id
        and public.can_access_org_location(orders.org_id, orders.location_id)
    )
  );
create policy "Restaurant payments: members read authorized orders"
  on public.restaurant_order_payments for select
  using (
    public.is_org_member(org_id)
    and exists (
      select 1 from public.restaurant_orders orders
      where orders.org_id = restaurant_order_payments.org_id
        and orders.id = restaurant_order_payments.order_id
        and public.can_access_org_location(orders.org_id, orders.location_id)
    )
  );

create or replace function public.create_restaurant_order(
  p_org_id uuid,
  p_location_id uuid,
  p_order_type text,
  p_table_id uuid,
  p_customer_name text,
  p_customer_phone text,
  p_delivery_address text,
  p_notes text,
  p_items jsonb,
  p_created_by uuid
)
returns public.restaurant_orders
language plpgsql
security definer
set search_path = public
as $$
declare
  created_order public.restaurant_orders;
  item jsonb;
  menu_item public.restaurant_menu_items;
  item_quantity numeric(10,2);
  calculated_subtotal numeric(12,2) := 0;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Only the service role can create restaurant orders.';
  end if;
  if p_order_type not in ('dine_in', 'takeaway', 'delivery') then
    raise exception 'Choose a valid restaurant order type.';
  end if;
  if p_order_type = 'delivery' and length(btrim(coalesce(p_delivery_address, ''))) = 0 then
    raise exception 'A delivery address is required for delivery orders.';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Add at least one menu item to the order.';
  end if;
  if not exists (
    select 1 from public.business_locations location
    where location.id = p_location_id and location.org_id = p_org_id and location.is_active
  ) then
    raise exception 'The selected restaurant location is not active for this organization.';
  end if;
  if p_order_type = 'dine_in' then
    if p_table_id is null or not exists (
      select 1 from public.restaurant_tables dining_table
      where dining_table.id = p_table_id
        and dining_table.org_id = p_org_id
        and dining_table.location_id = p_location_id
        and dining_table.is_active
    ) then
      raise exception 'Choose an active table at the selected location.';
    end if;
  elsif p_table_id is not null then
    raise exception 'Only dine-in orders can be assigned to a table.';
  end if;

  insert into public.restaurant_orders (
    org_id, location_id, order_type, table_id, customer_name, customer_phone, delivery_address,
    notes, subtotal, total, created_by
  ) values (
    p_org_id, p_location_id, p_order_type, p_table_id, nullif(btrim(p_customer_name), ''),
    nullif(btrim(p_customer_phone), ''), nullif(btrim(p_delivery_address), ''), nullif(btrim(p_notes), ''), 0, 0, p_created_by
  ) returning * into created_order;

  for item in select value from jsonb_array_elements(p_items)
  loop
    if jsonb_typeof(item) <> 'object' then
      raise exception 'Each order item must be an object.';
    end if;
    item_quantity := (item->>'quantity')::numeric;
    if item_quantity <= 0 or item_quantity > 999 then
      raise exception 'Order item quantities must be greater than zero and no more than 999.';
    end if;
    select * into menu_item
    from public.restaurant_menu_items
    where id = (item->>'menu_item_id')::uuid
      and org_id = p_org_id
      and is_active;
    if not found then
      raise exception 'A selected menu item is no longer active.';
    end if;
    calculated_subtotal := calculated_subtotal + menu_item.price * item_quantity;
    insert into public.restaurant_order_items (
      org_id, order_id, menu_item_id, item_name, unit_price, quantity, line_total, notes
    ) values (
      p_org_id, created_order.id, menu_item.id, menu_item.name, menu_item.price,
      item_quantity, menu_item.price * item_quantity, nullif(btrim(item->>'notes'), '')
    );
  end loop;

  update public.restaurant_orders
  set subtotal = calculated_subtotal, total = calculated_subtotal, updated_at = now()
  where id = created_order.id
  returning * into created_order;
  return created_order;
end;
$$;

create or replace function public.record_restaurant_payment(
  p_org_id uuid,
  p_order_id uuid,
  p_amount numeric,
  p_payment_method text,
  p_received_by uuid
)
returns public.restaurant_orders
language plpgsql
security definer
set search_path = public
as $$
declare
  target_order public.restaurant_orders;
  paid_total numeric(12,2);
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Only the service role can record restaurant payments.';
  end if;
  if p_amount <= 0 or p_payment_method not in ('cash', 'card', 'mobile_money', 'other') then
    raise exception 'Enter a valid payment amount and method.';
  end if;

  select * into target_order
  from public.restaurant_orders
  where id = p_order_id and org_id = p_org_id
  for update;
  if not found then
    raise exception 'Restaurant order not found.';
  end if;
  if target_order.status = 'cancelled' then
    raise exception 'Payments cannot be recorded against a cancelled order.';
  end if;

  select coalesce(sum(amount), 0) into paid_total
  from public.restaurant_order_payments
  where org_id = p_org_id and order_id = p_order_id;
  if p_amount > target_order.total - paid_total then
    raise exception 'Payment exceeds the outstanding order balance.';
  end if;

  insert into public.restaurant_order_payments (org_id, order_id, amount, payment_method, received_by)
  values (p_org_id, p_order_id, p_amount, p_payment_method, p_received_by);
  paid_total := paid_total + p_amount;
  update public.restaurant_orders
  set payment_status = case
        when paid_total >= total then 'paid'
        when paid_total > 0 then 'partial'
        else 'unpaid'
      end,
      updated_at = now()
  where id = p_order_id
  returning * into target_order;
  return target_order;
end;
$$;

revoke all on function public.create_restaurant_order(uuid, uuid, text, uuid, text, text, text, text, jsonb, uuid) from public, anon, authenticated;
revoke all on function public.record_restaurant_payment(uuid, uuid, numeric, text, uuid) from public, anon, authenticated;
grant execute on function public.create_restaurant_order(uuid, uuid, text, uuid, text, text, text, text, jsonb, uuid) to service_role;
grant execute on function public.record_restaurant_payment(uuid, uuid, numeric, text, uuid) to service_role;

commit;
